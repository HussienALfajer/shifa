// Generates packages/i18n/generated from the Arabic source:
//   keys.ts         — a key union per namespace (typed i18next keys for the web apps)
//   arb/app_ar.arb  — Flutter gen-l10n input: `<namespace><Key>` names, ICU text as written,
//                     placeholders declared with their types.
// `generate()` is pure (tests use it); the CLI is what the `i18n` drift check runs:
//   node packages/i18n/scripts/generate.ts [outDir] [localesDir]
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseMessage, placeholders } from '../src/icu.ts';
import { BASE_LOCALE, loadSources, type Sources } from '../src/sources.ts';

const HEADER = '// Generated by packages/i18n/scripts/generate.ts from src/locales. Do not edit.';

function pascal(text: string): string {
  return text
    .split('_')
    .filter((part) => part !== '')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

/** `common` + `not_found` → `commonNotFound` */
export function arbName(namespace: string, key: string): string {
  return namespace + pascal(key);
}

function sorted(keys: Iterable<string>): string[] {
  return [...keys].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

function arb(sources: Sources, locale: string): string {
  const doc: Record<string, unknown> = { '@@locale': locale };
  const origin = new Map<string, string>();
  const namespaces = sources[locale] ?? {};
  for (const namespace of sorted(Object.keys(namespaces))) {
    const messages = namespaces[namespace] ?? {};
    for (const key of sorted(Object.keys(messages))) {
      const message = messages[key] ?? '';
      const name = arbName(namespace, key);
      const source = `${namespace}.${key}`;
      const clash = origin.get(name);
      if (clash !== undefined) throw new Error(`${source} and ${clash} both map to ${name}`);
      origin.set(name, source);
      const types = placeholders(parseMessage(message));
      doc[name] = message;
      doc[`@${name}`] =
        types.size === 0
          ? { description: source }
          : {
              description: source,
              placeholders: Object.fromEntries([...types].map(([n, type]) => [n, { type }])),
            };
    }
  }
  return `${JSON.stringify(doc, null, 2)}\n`;
}

function keys(sources: Sources): string {
  const namespaces = sources[BASE_LOCALE] ?? {};
  const names = sorted(Object.keys(namespaces));
  const lines = [
    HEADER,
    `export const NAMESPACES = [${names.map((n) => `'${n}'`).join(', ')}] as const;`,
  ];
  lines.push('export type Namespace = (typeof NAMESPACES)[number];');
  for (const namespace of names) {
    const members = sorted(Object.keys(namespaces[namespace] ?? {})).map((k) => `\n  | '${k}'`);
    lines.push(`export type ${pascal(namespace)}Key =${members.join('') || ' never'};`);
  }
  lines.push('export interface MessageKeys {');
  for (const namespace of names) lines.push(`  ${namespace}: ${pascal(namespace)}Key;`);
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

/** Output path (relative to the generated directory) → file content. */
export function generate(sources: Sources): Record<string, string> {
  return { 'arb/app_ar.arb': arb(sources, BASE_LOCALE), 'keys.ts': keys(sources) };
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outDir = resolve(process.argv[2] ?? join(import.meta.dirname, '..', 'generated'));
  const files = generate(loadSources(process.argv[3]));
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(outDir, path)), { recursive: true });
    writeFileSync(join(outDir, path), text);
  }
}
