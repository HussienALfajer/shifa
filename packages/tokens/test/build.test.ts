// Criterion 2: the build turns the token source into CSS custom properties, a Tailwind v4
// theme and a Dart file.
import { beforeAll, describe, expect, it } from 'vitest';
import { build, OUTPUTS } from '../scripts/build.ts';
import { loadSources } from '../src/index.ts';
import { validSources } from './fixture.ts';

/** The body of the first `selector { ... }` block. */
function block(css: string, selector: string): string {
  const start = css.indexOf(`${selector} {`);
  expect(start, `${selector} block`).toBeGreaterThanOrEqual(0);
  return css.slice(start, css.indexOf('\n}', start));
}

describe('build (fixture)', () => {
  let files: Record<string, string>;
  let css: string;
  let tailwind: string;
  let dart: string;

  beforeAll(async () => {
    files = await build(validSources());
    css = files[OUTPUTS.css] ?? '';
    tailwind = files[OUTPUTS.tailwind] ?? '';
    dart = files[OUTPUTS.dart] ?? '';
  });

  it('writes exactly the four outputs at their repository paths', () => {
    expect(OUTPUTS).toEqual({
      css: 'packages/tokens/generated/css/tokens.css',
      tailwind: 'packages/tokens/generated/css/tailwind-theme.css',
      dart: 'packages/shifa_ui/lib/src/generated/tokens.g.dart',
      designSystem: 'packages/tokens/generated/design-system/tokens.json',
    });
    expect(Object.keys(files).sort()).toEqual(Object.values(OUTPUTS).sort());
  });

  it('every output says it is generated and ends with a newline', () => {
    for (const text of Object.values(files)) {
      expect(text).toMatch(/Generated by packages\/tokens\/scripts\/build\.ts/);
      expect(text.endsWith('\n')).toBe(true);
      expect(text).not.toContain('\r');
    }
  });

  it('is deterministic', async () => {
    expect(await build(validSources())).toEqual(files);
  });

  it('the CSS has the light values on :root, every layer included', () => {
    const root = block(css, ':root');
    expect(root).toContain('--shifa-color-white: #ffffff;');
    expect(root).toContain('--shifa-color-bg-surface: #ffffff;');
    expect(root).toContain('--shifa-color-brand-on-primary: #ffffff;');
    expect(root).toContain('--shifa-button-primary-bg: #1f6f5c;');
    expect(root).toContain('--shifa-space-8: 32px;');
    expect(root).toContain('--shifa-size-control-md: 44px;');
    expect(root).toContain('--shifa-motion-duration-fast: 120ms;');
  });

  it('the dark block holds the values that change in dark, and only those', () => {
    const dark = block(css, "[data-theme='dark']");
    expect(dark).toContain('--shifa-color-bg-surface: #101a17;');
    expect(dark).toContain('--shifa-color-text-default: #e8f2ee;');
    expect(dark).toContain('--shifa-color-status-success-fg: #7ccbb4;');
    // A component token follows the brand colour it points at.
    expect(dark).toContain('--shifa-button-primary-bg: #7ccbb4;');
    expect(dark).not.toContain('--shifa-color-white');
    expect(dark).not.toContain('--shifa-space-8');
    expect(dark).not.toContain('--shifa-size-control-md');
  });

  it('the compact block holds the values that change in compact, and only those', () => {
    const compact = block(css, "[data-density='compact']");
    expect(compact).toContain('--shifa-size-control-md: 32px;');
    expect(compact).toContain('--shifa-button-height: 32px;');
    expect(compact).not.toContain('--shifa-color');
    expect(compact).not.toContain('--shifa-space-8');
  });

  it('the Tailwind theme maps theme names to the custom properties', () => {
    expect(tailwind).toContain('@theme inline {');
    expect(tailwind).toContain('--color-*: initial;');
    expect(tailwind).toContain('--color-bg-surface: var(--shifa-color-bg-surface);');
    expect(tailwind).toContain('--color-brand-primary: var(--shifa-color-brand-primary);');
    expect(tailwind).toContain('--color-status-success-fg: var(--shifa-color-status-success-fg);');
    expect(tailwind).toContain('--spacing-8: var(--shifa-space-8);');
  });

  it('the Tailwind theme offers no primitive colour', () => {
    expect(tailwind).not.toContain('--color-white');
    expect(tailwind).not.toContain('--color-green-600');
  });

  it('the Dart file has the light and the dark colours under the same names', () => {
    const light = block(dart, 'abstract final class ShifaColorsLight');
    const dark = block(dart, 'abstract final class ShifaColorsDark');
    expect(light).toContain('static const Color colorBgSurface = Color(0xFFFFFFFF);');
    expect(dark).toContain('static const Color colorBgSurface = Color(0xFF101A17);');
    expect(light).toContain('static const Color colorBrandOnPrimary = Color(0xFFFFFFFF);');
    expect(light).toContain('static const Color buttonPrimaryBg = Color(0xFF1F6F5C);');
    const names = (text: string) =>
      [...text.matchAll(/static const Color (\w+)/g)].map((m) => m[1]);
    expect(names(dark)).toEqual(names(light));
    expect(light).not.toContain('colorWhite');
  });

  it('the Dart file has both densities and the shared values', () => {
    const comfortable = block(dart, 'abstract final class ShifaDensityComfortable');
    const compact = block(dart, 'abstract final class ShifaDensityCompact');
    expect(comfortable).toContain('static const double sizeControlMd = 44;');
    expect(compact).toContain('static const double sizeControlMd = 32;');
    expect(compact).toContain('static const double buttonHeight = 32;');
    const shared = block(dart, 'abstract final class ShifaTokens');
    expect(shared).toContain('static const double space8 = 32;');
    expect(shared).toContain(
      'static const Duration motionDurationFast = Duration(milliseconds: 120);',
    );
    expect(shared).not.toContain('sizeControlMd');
  });

  it('a broken source is refused', async () => {
    const sources = validSources();
    sources.pairs = [];
    await expect(build(sources)).rejects.toThrow(/no contrast pair/);
  });
});

describe('build (the token source)', () => {
  let files: Record<string, string>;

  beforeAll(async () => {
    files = await build(loadSources());
  });

  it('has the design doc light values', () => {
    const root = block(files[OUTPUTS.css] ?? '', ':root');
    expect(root).toContain('--shifa-color-bg-app: #fbf8f1;');
    expect(root).toContain('--shifa-color-text-default: #1d2a26;');
    expect(root).toContain('--shifa-color-brand-primary: #1f6f5c;');
    expect(root).toContain('--shifa-color-brand-accent: #c8a24a;');
  });

  it('has a dark and a compact block', () => {
    const css = files[OUTPUTS.css] ?? '';
    expect(block(css, "[data-theme='dark']")).toContain('--shifa-color-bg-app:');
    expect(block(css, "[data-density='compact']")).toContain('--shifa-');
  });

  it('writes shadows, font stacks and easings as CSS values', () => {
    const root = block(files[OUTPUTS.css] ?? '', ':root');
    expect(root).toMatch(/--shifa-elevation-\w+: \d+px \d+px \d+px -?\d+px rgb\(/);
    expect(root).toMatch(/--shifa-font-family-\w+: 'Shifa Sans Arabic', /);
    expect(root).toMatch(/--shifa-motion-easing-\w+: cubic-bezier\(/);
  });

  it('gives Dart the same colour names in both themes', () => {
    const dart = files[OUTPUTS.dart] ?? '';
    const names = (cls: string) =>
      [...block(dart, `abstract final class ${cls}`).matchAll(/static const Color (\w+)/g)].map(
        (m) => m[1],
      );
    expect(names('ShifaColorsLight').length).toBeGreaterThan(30);
    expect(names('ShifaColorsDark')).toEqual(names('ShifaColorsLight'));
  });
});
