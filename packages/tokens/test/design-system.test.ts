// Spec 0.4, criterion 12: the fourth output of the tokens build is the Shifa Design System's
// tokens file, in the Design System type's list format (not DTCG): colours per theme with a
// usage note, type styles and fonts, spacing, radius, shadows. The design project mirrors it.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';
import { build, OUTPUTS } from '../scripts/build.ts';
import { type DesignSystemTokens, loadFonts } from '../scripts/design-system.ts';
import { loadSources } from '../src/index.ts';
import { validSources } from './fixture.ts';

const NAME = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$/;
const HEX = /^#[0-9a-f]{6}([0-9a-f]{2})?$/;
const ALIAS = /^\{([^{}]+)\}$/;
const LENGTH = /^-?\d+(\.\d+)?px$/;
const THEMES = ['light', 'dark'] as const;
type Theme = (typeof THEMES)[number];

interface Entry {
  name: string;
  value: unknown;
  usage?: string;
}

/** Every `{tokens: [...]}` family of the file (all but `type`). */
function families(ds: DesignSystemTokens): [string, Entry[]][] {
  return Object.entries(ds)
    .filter(([key, family]) => key !== 'type' && key !== 'meta' && typeof family === 'object')
    .filter(([, family]) => Array.isArray((family as { tokens?: unknown }).tokens))
    .map(([key, family]) => [key, (family as { tokens: Entry[] }).tokens]);
}

/** The literal colour of a colour token in a theme, following aliases as the page does. */
function resolveColour(colours: Map<string, Entry>, name: string, theme: Theme): string {
  const seen: string[] = [];
  let current = name;
  for (;;) {
    if (seen.includes(current)) throw new Error(`alias cycle ${[...seen, current].join(' → ')}`);
    seen.push(current);
    const entry = colours.get(current);
    if (entry === undefined) throw new Error(`${name}: alias of a missing token ${current}`);
    const raw = entry.value;
    const value =
      typeof raw === 'string'
        ? raw
        : ((raw as Record<string, string>)[theme] ?? (raw as Record<string, string>)['light']);
    const alias = ALIAS.exec(String(value));
    if (alias === null) return String(value);
    current = alias[1] ?? '';
  }
}

/** `--name: value;` declarations of one block of tokens.css. */
function declarations(css: string, selector: string): Map<string, string> {
  const start = css.indexOf(`${selector} {`);
  const body = css.slice(start, css.indexOf('\n}', start));
  return new Map([...body.matchAll(/--([\w-]+): ([^;]+);/g)].map((m) => [m[1] ?? '', m[2] ?? '']));
}

describe('the design-system output (the token source)', () => {
  let files: Record<string, string>;
  let ds: DesignSystemTokens;
  let colours: Map<string, Entry>;

  beforeAll(async () => {
    files = await build(loadSources(), loadFonts());
    ds = JSON.parse(files[OUTPUTS.designSystem] ?? '{}') as DesignSystemTokens;
    colours = new Map(ds.color.tokens.map((t) => [t.name, t as Entry]));
  });

  it('is the fourth output, in packages/tokens/generated', () => {
    expect(OUTPUTS.designSystem).toBe('packages/tokens/generated/design-system/tokens.json');
    expect(Object.keys(files).sort()).toEqual(Object.values(OUTPUTS).sort());
  });

  it('is JSON with two-space indent and a final newline, and says it is generated', () => {
    const text = files[OUTPUTS.designSystem] ?? '';
    expect(text).toBe(`${JSON.stringify(JSON.parse(text), null, 2)}\n`);
    expect(ds.meta.generated).toMatch(/Generated by packages\/tokens\/scripts\/build\.ts/);
    expect(ds.meta.source).toBe('code');
  });

  it('is named Shifa and has the light theme first, then dark', () => {
    expect(ds.name).toBe('Shifa');
    expect(ds.color.themes).toEqual([
      { id: 'light', name: 'Light' },
      { id: 'dark', name: 'Dark' },
    ]);
  });

  it('every family but type is a list of {name, value, usage}', () => {
    const keys = families(ds).map(([key]) => key);
    for (const key of ['color', 'spacing', 'radius', 'shadow']) expect(keys).toContain(key);
    expect(
      Object.keys(ds)
        .filter((k) => !['name', 'version', 'meta', 'type'].includes(k))
        .sort(),
    ).toEqual(keys.sort());
    for (const [key, tokens] of families(ds)) {
      expect(tokens.length, key).toBeGreaterThan(0);
      expect(tokens.length, key).toBeLessThanOrEqual(key === 'color' ? 600 : 60);
      for (const t of tokens) {
        expect(Object.keys(t).sort(), `${key} ${t.name}`).toEqual(['name', 'usage', 'value']);
      }
    }
  });

  it('names are valid and unique across every family', () => {
    const names = families(ds).flatMap(([, tokens]) => tokens.map((t) => t.name));
    for (const name of names) expect(name).toMatch(NAME);
    expect(new Set(names).size).toBe(names.length);
  });

  it('names are the CSS custom property names, so a drawing ports to code as it is', () => {
    const root = declarations(files[OUTPUTS.css] ?? '', ':root');
    for (const [, tokens] of families(ds)) {
      for (const t of tokens) expect(root.has(t.name), t.name).toBe(true);
    }
  });

  it('every token has a usage note', () => {
    for (const [key, tokens] of families(ds)) {
      for (const t of tokens) expect(t.usage?.trim(), `${key} ${t.name}`).toBeTruthy();
      for (const t of tokens) expect((t.usage ?? '').length, t.name).toBeLessThanOrEqual(1000);
    }
  });

  it('every colour resolves in both themes, with no alias to a missing token or itself', () => {
    for (const t of ds.color.tokens) {
      for (const theme of THEMES)
        expect(resolveColour(colours, t.name, theme), `${t.name} ${theme}`).toMatch(HEX);
    }
  });

  it('every semantic and brand colour states its light and its dark value', () => {
    const themed = ds.color.tokens.filter((t) =>
      /^shifa-color-(bg|text|border|nav|brand|status|icon)-/.test(t.name),
    );
    expect(themed.length).toBeGreaterThan(30);
    for (const t of themed) {
      expect(typeof t.value, t.name).toBe('object');
      expect(Object.keys(t.value as object).sort(), t.name).toEqual(['dark', 'light']);
    }
  });

  it('colours are the values of tokens.css in light and in dark', () => {
    const css = files[OUTPUTS.css] ?? '';
    const light = declarations(css, ':root');
    const dark = new Map([...light, ...declarations(css, "[data-theme='dark']")]);
    for (const t of ds.color.tokens) {
      const expected = { light: light.get(t.name), dark: dark.get(t.name) };
      for (const theme of THEMES) {
        const value = expected[theme] ?? '';
        if (!value.startsWith('#')) continue; // translucent: rgb() in CSS, #rrggbbaa here
        expect(resolveColour(colours, t.name, theme), `${t.name} ${theme}`).toBe(value);
      }
    }
  });

  it('a translucent colour is written as #rrggbbaa', () => {
    expect(resolveColour(colours, 'shifa-color-bg-overlay', 'light')).toMatch(/^#[0-9a-f]{8}$/);
    expect(resolveColour(colours, 'shifa-color-bg-overlay', 'dark')).toMatch(/^#[0-9a-f]{8}$/);
  });

  it('spacing and radius are px lengths; shadows are box-shadow strings without var()', () => {
    for (const t of ds.spacing.tokens) expect(t.value, t.name).toMatch(LENGTH);
    for (const t of ds.radius.tokens) expect(t.value, t.name).toMatch(LENGTH);
    for (const t of ds.shadow.tokens) {
      expect(t.value, t.name).toMatch(/^(-?\d+px ){4}#[0-9a-f]{8}(, (-?\d+px ){4}#[0-9a-f]{8})*$/);
    }
    const names = (list: Entry[]) => list.map((t) => t.name);
    expect(names(ds.spacing.tokens)).toContain('shifa-space-4');
    expect(names(ds.radius.tokens)).toContain('shifa-shape-radius-control');
    expect(names(ds.shadow.tokens)).toContain('shifa-shadow-card');
    expect(names(ds.shadow.tokens)).toContain('shifa-shadow-focus');
  });

  it('a value that changes in compact density says so in its usage', () => {
    const control = families(ds)
      .flatMap(([, tokens]) => tokens)
      .find((t) => t.name === 'shifa-size-control-md');
    expect(control?.value).toBe('44px');
    expect(control?.usage).toMatch(/Compact: 32px\./);
  });

  it('type: the three families, the self-hosted fonts and the named styles', () => {
    expect(Object.keys(ds.type.families).sort()).toEqual(['mono', 'sans', 'serif']);
    expect(ds.type.families['sans']).toBe("'IBM Plex Sans Arabic', system-ui, sans-serif");
    const groups = ds.type.groups.map((g) => g.name);
    expect(groups).toEqual(['Titles', 'Labels', 'Paragraphs']);
    const styles = ds.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, group: g })));
    expect(styles.map((s) => s.name)).toContain('title-display');
    for (const s of styles) {
      expect(s.name).toMatch(NAME);
      expect(s.fontSize, s.name).toMatch(LENGTH);
      expect(typeof s.lineHeight, s.name).toBe('number');
      expect(s.lineHeight, s.name).toBeLessThan(10);
      expect([400, 500, 600, 700]).toContain(s.fontWeight);
      expect(Object.keys(ds.type.families)).toContain(s.family ?? s.group.family);
      expect(s.usage.trim(), s.name).toBeTruthy();
    }
    expect(new Set(styles.map((s) => s.name)).size).toBe(styles.length);
    const display = styles.find((s) => s.name === 'title-display');
    expect([display?.fontSize, display?.fontWeight]).toEqual(['44px', 700]);
  });

  it('fonts are the static TTFs of fonts.json, one per family and weight', () => {
    const fonts = ds.type.fonts;
    expect(fonts.map((f) => `${f.family} ${f.weight}`)).toEqual([
      'IBM Plex Sans Arabic 400',
      'IBM Plex Sans Arabic 500',
      'IBM Plex Sans Arabic 600',
      'IBM Plex Sans Arabic 700',
      'Noto Naskh Arabic 400',
      'Noto Naskh Arabic 700',
    ]);
    for (const f of fonts) {
      expect(f.file).toMatch(/^fonts\/[a-z0-9-]+\.ttf$/);
      expect(f.style).toBe('normal');
      // fonts/<family id>-<weight>.ttf is a copy of packages/tokens/fonts/<family id>/ttf/<same>.
      const file = f.file.slice('fonts/'.length);
      const id = file.replace(/-\d+\.ttf$/, '');
      const source = join(import.meta.dirname, '..', 'fonts', id, 'ttf', file);
      expect(readFileSync(source).length, source).toBeLessThan(1024 * 1024);
      expect(Object.keys(f).sort()).toEqual(['family', 'file', 'style', 'weight']);
    }
  });

  it('is deterministic', async () => {
    const again = await build(loadSources(), loadFonts());
    expect(again[OUTPUTS.designSystem]).toBe(files[OUTPUTS.designSystem]);
  });
});

describe('the design-system output (fixture)', () => {
  it('builds without fonts and puts a component colour as an alias of what it follows', async () => {
    const files = await build(validSources());
    const ds = JSON.parse(files[OUTPUTS.designSystem] ?? '{}') as DesignSystemTokens;
    expect(ds.type.fonts).toEqual([]);
    const bg = ds.color.tokens.find((t) => t.name === 'shifa-button-primary-bg');
    expect(bg?.value).toBe('{shifa-color-brand-primary}');
    const surface = ds.color.tokens.find((t) => t.name === 'shifa-color-bg-surface');
    expect(surface?.value).toEqual({
      light: '{shifa-color-white}',
      dark: '{shifa-color-night-900}',
    });
    const white = ds.color.tokens.find((t) => t.name === 'shifa-color-white');
    expect(white?.value).toBe('#ffffff');
  });
});
